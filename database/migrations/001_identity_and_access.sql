create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  display_name text,
  primary_prayer_house_id smallint references public.prayer_houses(id),
  phone_private text,
  public_bio text,
  profile_visibility text not null default 'public'
    check (profile_visibility in ('public', 'members', 'private')),
  membership_status text not null default 'pending'
    check (membership_status in ('pending', 'approved', 'suspended')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- System access is separate from elected/appointed youth-group offices.
-- The four Super Administrator office-holders receive the same super_admin level.
create table if not exists public.admin_assignments (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  access_level text not null
    check (access_level in ('prayer_house_admin', 'parish_admin', 'super_admin')),
  prayer_house_id smallint references public.prayer_houses(id),
  super_admin_office text,
  is_active boolean not null default true,
  assigned_by uuid references public.profiles(id),
  created_at timestamptz not null default now(),
  check (
    (access_level = 'prayer_house_admin' and prayer_house_id is not null and super_admin_office is null)
    or
    (access_level = 'parish_admin' and prayer_house_id is null and super_admin_office is null)
    or
    (access_level = 'super_admin' and prayer_house_id is null
      and super_admin_office in ('Youth Chaplain', 'Youth Matron', 'Youth Patron', 'Parish Moderator'))
  )
);

create unique index if not exists admin_assignments_one_active_level
  on public.admin_assignments (user_id, access_level, coalesce(prayer_house_id, 0))
  where is_active;

create table if not exists public.appointments (
  id uuid primary key default gen_random_uuid(),
  member_id uuid not null references public.profiles(id) on delete cascade,
  office_name text not null,
  scope text not null check (scope in ('parish', 'prayer_house')),
  prayer_house_id smallint references public.prayer_houses(id),
  verification_status text not null default 'pending'
    check (verification_status in ('pending', 'verified', 'rejected')),
  nominated_at timestamptz not null default now(),
  verified_by uuid references public.profiles(id),
  verified_at timestamptz,
  effective_from date,
  effective_until date,
  created_at timestamptz not null default now(),
  check (
    (scope = 'parish' and prayer_house_id is null)
    or (scope = 'prayer_house' and prayer_house_id is not null)
  ),
  check (
    (verification_status = 'verified' and verified_by is not null and verified_at is not null)
    or verification_status <> 'verified'
  ),
  check (effective_until is null or effective_from is null or effective_until >= effective_from)
);

create index if not exists profiles_house_status_idx
  on public.profiles (primary_prayer_house_id, membership_status);
create index if not exists admin_assignments_user_active_idx
  on public.admin_assignments (user_id, is_active);
create index if not exists appointments_member_status_idx
  on public.appointments (member_id, verification_status);
create index if not exists appointments_house_status_idx
  on public.appointments (prayer_house_id, verification_status);

-- SECURITY DEFINER helpers avoid recursive RLS checks when policies inspect
-- the administrative assignment table. The fixed search_path is intentional.
create or replace function private.is_super_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.admin_assignments aa
    where aa.user_id = auth.uid()
      and aa.access_level = 'super_admin'
      and aa.is_active = true
  );
$$;

create or replace function private.has_parish_admin_access()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.admin_assignments aa
    where aa.user_id = auth.uid()
      and aa.access_level in ('parish_admin', 'super_admin')
      and aa.is_active = true
  );
$$;

create or replace function private.is_house_admin(target_house_id smallint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select
    private.has_parish_admin_access()
    or exists (
      select 1
      from public.admin_assignments aa
      where aa.user_id = auth.uid()
        and aa.access_level = 'prayer_house_admin'
        and aa.prayer_house_id = target_house_id
        and aa.is_active = true
    );
$$;

alter table public.prayer_houses enable row level security;
alter table public.profiles enable row level security;
alter table public.admin_assignments enable row level security;
alter table public.appointments enable row level security;

-- Prayer-house names are public reference data.
drop policy if exists prayer_houses_public_read on public.prayer_houses;
create policy prayer_houses_public_read
  on public.prayer_houses for select
  to anon, authenticated
  using (is_active = true);

-- Profiles are private by default at this stage. Public directory access will
-- be added later through a deliberately limited view, never the raw table.
drop policy if exists profiles_read_self_or_authorised_admin on public.profiles;
create policy profiles_read_self_or_authorised_admin
  on public.profiles for select
  to authenticated
  using (
    id = auth.uid()
    or private.has_parish_admin_access()
    or (
      primary_prayer_house_id is not null
      and private.is_house_admin(primary_prayer_house_id)
    )
  );

-- A member can read their own access assignments; only Super Administrators
-- can inspect/manage the full assignment register.
drop policy if exists admin_assignments_read_self_or_super_admin on public.admin_assignments;
create policy admin_assignments_read_self_or_super_admin
  on public.admin_assignments for select
  to authenticated
  using (user_id = auth.uid() or private.is_super_admin());

drop policy if exists admin_assignments_super_admin_manage on public.admin_assignments;
create policy admin_assignments_super_admin_manage
  on public.admin_assignments for all
  to authenticated
  using (private.is_super_admin())
  with check (private.is_super_admin());

-- Members may submit a pending appointment claim for themselves. Verification
-- and rejection remain administrator-controlled and will be implemented through
-- a trusted server-side action in a later migration.
drop policy if exists appointments_read_self_or_authorised_admin on public.appointments;
create policy appointments_read_self_or_authorised_admin
  on public.appointments for select
  to authenticated
  using (
    member_id = auth.uid()
    or private.has_parish_admin_access()
    or (prayer_house_id is not null and private.is_house_admin(prayer_house_id))
  );

drop policy if exists appointments_submit_own_pending_claim on public.appointments;
create policy appointments_submit_own_pending_claim
  on public.appointments for insert
  to authenticated
  with check (
    member_id = auth.uid()
    and verification_status = 'pending'
    and verified_by is null
    and verified_at is null
  );

revoke all on function private.is_super_admin() from public, anon;
revoke all on function private.has_parish_admin_access() from public, anon;
revoke all on function private.is_house_admin(smallint) from public, anon;
grant execute on function private.is_super_admin() to authenticated;
grant execute on function private.has_parish_admin_access() to authenticated;
grant execute on function private.is_house_admin(smallint) to authenticated;

-- Explicit minimum Data API grants; RLS remains the row-level gate.
grant select on public.prayer_houses to anon, authenticated;
grant select on public.profiles to authenticated;
grant select, insert, update, delete on public.admin_assignments to authenticated;
grant select, insert on public.appointments to authenticated;

